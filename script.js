/* ===========================
   NAVIGATION / UI HELPERS
   =========================== */
function initDashboardEvents() {
  // menu items
  menuItems.forEach(item => {
    item.addEventListener('click', function () {
      const targetContent = this.getAttribute('data-content');
      menuItems.forEach(mi => mi.classList.remove('active'));
      this.classList.add('active');
      contentSections.forEach(section => section.classList.remove('active'));
      const el = document.getElementById(`${targetContent}-content`);
      if (el) el.classList.add('active');

      const menuText = this.querySelector('span')?.textContent || '';
      if (pageTitle) pageTitle.textContent = menuText;
      // save active menu
      localStorage.setItem('activeMenu', targetContent);
    });
  });

  // menu toggle
  if (menuToggle) menuToggle.addEventListener('click', () => sidebar.classList.toggle('collapsed'));

  // logout btn in header
  const logoutBtn = document.getElementById('logoutBtn');
  if (logoutBtn) logoutBtn.addEventListener('click', logout);

  // modal open buttons (assuming existence of buttons with ids)
  const tambahStaffHatoribet = document.getElementById('tambahStaffHatoribet');
  const tambahStaffLivitoto = document.getElementById('tambahStaffLivitoto');
  const tambahStaffHmd29 = document.getElementById('tambahStaffHmd29');

  if (tambahStaffHatoribet) tambahStaffHatoribet.addEventListener('click', () => openStaffModal('hatoribet'));
  if (tambahStaffLivitoto) tambahStaffLivitoto.addEventListener('click', () => openStaffModal('livitoto'));
  if (tambahStaffHmd29) tambahStaffHmd29.addEventListener('click', () => openStaffModal('hmd29'));

  if (cancelBtn) cancelBtn.addEventListener('click', closeStaffModal);

  // staffForm submit (tambah/edit)
  if (staffForm) staffForm.addEventListener('submit', handleStaffFormSubmit);

  // restore active menu if any
  const activeMenu = localStorage.getItem('activeMenu');
  if (activeMenu) {
    const target = document.querySelector(`.menu-item[data-content="${activeMenu}"]`);
    if (target) target.click();
  }
}

