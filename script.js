/* ===========================
   AUTH: cek status login
   =========================== */
onAuthStateChanged(auth, async (user) => {
  if (!user) {
    // belum login -> kembali ke halaman login
    window.location.href = 'index.html';
    return;
  }

  currentUser = user;
  // ambil doc user di koleksi 'users' untuk dapatkan role & flag canEdit
  try {
    const userDocRef = doc(db, 'users', user.uid);
    const userSnap = await getDoc(userDocRef);
    if (userSnap.exists()) {
      currentUserDoc = userSnap.data();
    } else {
      // jika belum ada doc (kemungkinan register belum membuat doc), buat default doc
      const defaultRole = (user.email === 'admin@company.com') ? 'admin' : 'staff';
      await addDoc(collection(db, 'users'), { // created with autogenerated id if not created by register flow
        uid: user.uid,
        email: user.email,
        username: user.email.split('@')[0],
        role: defaultRole,
        canEdit: defaultRole === 'admin',
        createdAt: serverTimestamp()
      });
      // coba ambil lagi (sederhana)
      const q = query(collection(db, 'users'), where('uid', '==', user.uid));
      const qSnap = await getDocs(q);
      if (!qSnap.empty) currentUserDoc = qSnap.docs[0].data();
    }
  } catch (err) {
    console.warn('Gagal ambil user doc:', err.message);
    // fallback ke minimal info
    currentUserDoc = { email: user.email, username: user.email.split('@')[0], role: (user.email === 'admin@company.com') ? 'admin' : 'staff', canEdit: user.email === 'admin@company.com' };
  }

  isAdminOrCanEdit = !!(currentUserDoc && currentUserDoc.canEdit);

  // Update header/profile UI (jaga sesuai elemen di HTML)
  try {
    const userProfileImg = document.querySelector('.user-profile img');
    const userProfileName = document.querySelector('.user-profile span');
    if (userProfileImg) userProfileImg.src = currentUserDoc.avatar || `https://ui-avatars.com/api/?name=${encodeURIComponent(currentUserDoc.username)}&background=0366d6&color=fff`;
    if (userProfileName) userProfileName.textContent = currentUserDoc.username || currentUser.email.split('@')[0];
    const userEmailElem = document.getElementById('userEmail');
    if (userEmailElem) userEmailElem.textContent = currentUser.email;
  } catch (e) { /* ignore */ }

  // aktifkan event dashboard & load data
  initDashboardEvents();
  await loadAllStaff();
  await loadActivities();
  updateStats();
  applyPermissionsUI();
});

